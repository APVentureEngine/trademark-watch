def _open(req):
    try:
        with urllib.request.urlopen(req, timeout=300) as r:
            return r.status, dict(r.headers), r.read()
    except urllib.error.HTTPError as e:
        return e.code, dict(e.headers), e.read()


def api(method, path, form=None, jsonbody=None):
    url = API + path + ("?" if "?" not in path else "&") + "access_token=" + urllib.parse.quote(TOK)
    if jsonbody is not None:
        req = urllib.request.Request(url, data=json.dumps(jsonbody).encode(), method=method,
                                     headers={"Content-Type": "application/json"})
    else:
        req = urllib.request.Request(url, data=urllib.parse.urlencode(dict(form or {}), doseq=True).encode(),
                                     method=method)
    st, _, body = _open(req)
    try:
        return json.loads(body)
    except Exception:
        return {"success": False, "message": f"HTTP {st}: {body[:200]!r}"}


def get_product(pid):
    return api("GET", f"/v2/products/{urllib.parse.quote(pid, safe='')}").get("product") or {}


def upload_file(path):
    size = os.path.getsize(path)
    pre = api("POST", "/v2/files/presign", {"filename": os.path.basename(path), "file_size": size})
    if not pre.get("success"):
        raise SystemExit(f"presign failed: {pre}")
    parts = []
    with open(path, "rb") as fh:
        for p in pre["parts"]:
            st, hdrs, body = _open(urllib.request.Request(p["presigned_url"], data=fh.read(PART), method="PUT"))
            if st not in (200, 204):
                raise SystemExit(f"part {p['part_number']} PUT {st}: {body[:200]!r}")
            parts.append({"part_number": p["part_number"],
                          "etag": (hdrs.get("ETag") or hdrs.get("Etag") or "").strip('"')})
    done = api("POST", "/v2/files/complete",
               jsonbody={"upload_id": pre["upload_id"], "key": pre["key"], "parts": parts})
    if not done.get("success"):
        raise SystemExit(f"complete failed: {done}")
    return done["file_url"]


def replace_file(pid, path, display_name, body_text):
    p = get_product(pid)
    old_ids = [f["id"] for f in (p.get("files") or [])]
    page_id = (p.get("rich_content") or [{}])[0].get("id")
    url = upload_file(path)
    r = api("PUT", f"/v2/products/{urllib.parse.quote(pid, safe='')}",
            jsonbody={"files": [{"id": i} for i in old_ids] + [{"url": url, "display_name": display_name}]})
    if not r.get("success"):
        raise SystemExit(f"attach failed: {r}")
    new_id = [f["id"] for f in r["product"]["files"] if f["id"] not in old_ids][0]
    page = {"title": None, "description": {"type": "doc", "content": [
        {"type": "fileEmbed", "attrs": {"id": new_id, "uid": str(uuid.uuid4()), "collapsed": False}},
        {"type": "paragraph", "content": [{"type": "text", "text": body_text}]}]}}
    if page_id:
        page["id"] = page_id
    r2 = api("PUT", f"/v2/products/{urllib.parse.quote(pid, safe='')}",
             jsonbody={"files": [{"id": new_id}], "rich_content": [page]})
    if not r2.get("success"):
        raise SystemExit(f"swap failed: {r2}")
    back = get_product(pid)
    assert [f["id"] for f in back["files"]] == [new_id], "round-trip mismatch"
    return new_id


def set_cover(pid, image_url, replace=True):
    """Add a cover from a public URL; drop older ones so the listing shows the
    current artwork (covers are ordered, extras become a carousel)."""
    p = get_product(pid)
    old = [c.get("id") for c in (p.get("covers") or []) if c.get("id")]
    r = api("POST", f"/v2/products/{urllib.parse.quote(pid, safe='')}/covers", {"url": image_url})
    if not r.get("success"):
        raise SystemExit(f"cover failed: {r}")
    if replace:
        for guid in old:
            api("DELETE", f"/v2/products/{urllib.parse.quote(pid, safe='')}/covers/{guid}")
    return r


