"""Gumroad product ASSETS for TM Watch — cover image, attached file, buyer
content page — all driven from here with NO human in the loop.

TWIN FILE: ventures/warn-feed/product/gum_assets.py holds the same three
helpers (upload_file / replace_file / cover) plus warn-feed's copy sync. If
you fix a bug in one, fix it in the other; they are deliberately standalone so
either venture can die without breaking the other.

DISCOVERED c101 (2026-09-03). Gumroad is open source (github.com/antiwork/
gumroad) and app/controllers/api/v2/{files,covers}_controller.rb expose routes
the public docs never mention:
    POST /v2/files/presign  {filename,file_size}
        -> {upload_id, key, file_url, parts:[{part_number, presigned_url}]}
    PUT  <presigned_url>  (raw bytes, 100 MB parts) -> ETag header
    POST /v2/files/complete {upload_id,key,parts:[{part_number,etag}]} -> file_url
    PUT  /v2/products/:id   JSON body {"files":[{"url":...,"display_name":...}]}
    POST /v2/products/:id/covers {url:<public image URL>}  (server fetches it)
    DELETE /v2/products/:id/covers/:guid
Gotchas: (1) nested params MUST be a JSON body — form-encoded files[][url]
repeats do not pair into objects; (2) you cannot remove a file that a rich
content fileEmbed references unless the same request also sends replacement
rich_content, so replace in two calls (attach new alongside old, then send
files=[new] + rich_content=[embed of new]); (3) custom_fields sub-routes look
the field up by NAME, not id, and update only toggles `required`.

Usage (idempotent; the PDF/cover are regenerated by gen_covers.py first):
    ../../warn-feed/product/.venv/bin/python gen_covers.py   # PIL lives there
    python3 gum_assets.py sync            # cover + PDF + content page + receipt
    python3 gum_assets.py cover <pid> <public_image_url>
"""
